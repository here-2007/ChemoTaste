// Default high-quality culinary fallback photo
export const DEFAULT_INGREDIENT_PHOTO =
  'https://images.unsplash.com/photo-1546069901-ba9599a7e63c?auto=format&fit=crop&w=240&h=240&q=80';

export function getIngredientImageUrl(name: string): string {
  if (!name) return DEFAULT_INGREDIENT_PHOTO;
  const normalized = name.toLowerCase().trim();
  if (INGREDIENT_IMAGES[normalized]) {
    return INGREDIENT_IMAGES[normalized];
  }

  // Sort keys by descending length to match more specific multi-word ingredients first
  const keys = Object.keys(INGREDIENT_IMAGES).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (normalized.includes(key)) {
      return INGREDIENT_IMAGES[key];
    }
  }

  // Check significant word tokens (>= 3 chars)
  const tokens = normalized.split(/[\s,/-]+/).filter(t => t.length >= 3);
  for (const token of tokens) {
    if (INGREDIENT_IMAGES[token]) {
      return INGREDIENT_IMAGES[token];
    }
  }

  return DEFAULT_INGREDIENT_PHOTO;
}
